(async () => {
  const results = [], app = Folio.app;
  const assert = (test, passed, detail) => results.push({ test, passed: !!passed, ...(detail ? {detail} : {}) });
  const wait = async predicate => { for (let i=0;i<200;i++) { if (predicate()) return; await new Promise(r=>setTimeout(r,50)); } throw new Error('Timed out waiting for viewer state'); };
  app.page = 1;
  await wait(() => app.pdfDocument && app.pdfViewer.getPageView(0)?.renderingState === 3);
  assert('PDF worker loads all four pages', app.pagesCount === 4);
  assert('Opening a document does not mark it unsaved', !Folio.dirty());
  const canvas = document.querySelector('.page[data-page-number="1"] canvas');
  assert('First page renders real pixels', canvas && canvas.width > 100 && canvas.height > 100);
  await wait(() => document.querySelector('.page[data-page-number="1"] .textLayer')?.textContent.includes('clear space'));
  assert('Selectable text layer is rendered', document.querySelector('.page[data-page-number="1"] .textLayer').textContent.includes('clear space'));
  const outline = await app.pdfDocument.getOutline();
  assert('Document bookmarks are available', outline?.length === 4);
  const attachments = await app.pdfDocument.getAttachments();
  assert('Embedded attachment is available', !!(attachments?.get?.('Folio sample note.txt') || attachments?.['Folio sample note.txt']));
  app.eventBus.dispatch('find', { source: window, type: '', query: 'paperplane', phraseSearch: true, caseSensitive: false, entireWord: false, highlightAll: true, findPrevious: false, matchDiacritics: false });
  await wait(() => app.findController.pageMatches?.reduce((n,m)=>n+m.length,0) === 4);
  assert('Search finds matches across document', app.findController.pageMatches.reduce((n,m)=>n+m.length,0) === 4);
  app.pdfViewer.currentScaleValue = 'page-width'; await new Promise(r=>setTimeout(r,200));
  assert('Fit width adjusts zoom', app.pdfViewer.currentScaleValue === 'page-width' && app.pdfViewer.currentScale > 0);
  app.pdfViewer.pagesRotation = 90; assert('Page rotation works', app.pdfViewer.pagesRotation === 90);
  app.pdfViewer.pagesRotation = 0;
  app.pdfViewer.spreadMode = 1; assert('Facing page layout works', app.pdfViewer.spreadMode === 1); app.pdfViewer.spreadMode = 0;
  app.page = 4;
  await wait(() => app.pdfViewer.getPageView(3)?.renderingState === 3);
  const wide = await app.pdfDocument.getPage(4);
  assert('Mixed landscape page renders', app.page === 4 && wide.view[2] > wide.view[3]);
  Folio.setTheme('dark'); assert('Dark theme is applied', document.documentElement.dataset.folioTheme === 'dark');
  Folio.setTheme('light'); assert('Light theme is applied', document.documentElement.dataset.folioTheme === 'light');
  app.page = 3;
  await wait(() => document.querySelector('input[name="reader_name"]'));
  const field = document.querySelector('input[name="reader_name"]');
  field.value = 'Folio integration reader'; field.dispatchEvent(new Event('input',{bubbles:true})); field.dispatchEvent(new Event('change',{bubbles:true}));
  const objects = await app.pdfDocument.getFieldObjects();
  const readerField = (objects.get?.('reader_name') || objects.reader_name)[0];
  assert('PDF form input updates annotation storage', app.pdfDocument.annotationStorage.getValue(readerField.id,{}).value === 'Folio integration reader');
  assert('Unsaved form change is tracked', Folio.dirty() && !document.getElementById('changeBadge').hidden);
  const manager = app.pdfViewer._layerProperties.annotationEditorUIManager;
  await manager.updateMode(3);
  const layer = manager.getLayer(2);
  const editor = layer.createAndAddNewEditor({offsetX:120,offsetY:130},false);
  editor.editorDiv.innerText = 'Folio test annotation';
  editor.editorDiv.dispatchEvent(new Event('input',{bubbles:true})); editor.commit();
  window.folioTestEditor = editor;
  assert('Text annotation is created and stored', app.pdfDocument.annotationStorage.serializable.map.values().some(x=>x.value==='Folio test annotation'));
  await manager.updateMode(0);
  assert('Print service is available', app.supportsPrinting && typeof app.triggerPrinting === 'function');
  await wait(() => app.pdfViewer.pageViewsReady);
  app.beforePrint(); await app.printService.renderPages();
  assert('Print preparation renders all four pages', document.getElementById('printContainer').querySelectorAll('img').length === 4);
  app.afterPrint();
  assert('Annotation editing toolbar is available', !document.getElementById('editorModeButtons').hidden);
  const response = await fetch('https://example.com').then(()=>false,()=>true);
  assert('Viewer blocks remote network requests', response);
  return results;
})()
